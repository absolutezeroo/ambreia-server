       SUM(fd.`name` IS NULL) AS `introuvables`
FROM `nft_collection_items` i
JOIN `nft_collections` c ON c.`id` = i.`collection_id`
LEFT JOIN (SELECT DISTINCT `name` FROM `furniture_definitions` WHERE `deleted_at` IS NULL) fd
       ON fd.`name` = i.`product_code`
WHERE i.`deleted_at` IS NULL AND c.`deleted_at` IS NULL
GROUP BY c.`id`, c.`collection_code`, c.`name`
ORDER BY `introuvables` DESC, c.`collection_code`;

