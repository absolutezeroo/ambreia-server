-- Reprend les 243 collections du Collectors Guild d'Habbo, relevees sur le vrai serveur.
--
-- Source : le paquet NftCollections (entrant 3573 sur AIR-1.0.31) capture a l'ouverture de
-- l'onglet Collections. Il a ete decode octet par octet et consomme EXACTEMENT ses 125 906
-- octets de corps -- c'est la preuve que la lecture est juste et pas seulement plausible, et
-- au passage la verification que notre NftCollectionsMessageComposerSerializer ecrit deja la
-- meme structure qu'Habbo, champ pour champ.
--
-- Contenu : 243 collections, 1962 items, 1962 classnames distincts.
--
-- Ce que la lecture a tranche, et qui se decide ici :
--
--   1. 27 % des items ne sont PAS du mobilier : 488 vetements, 22 badges, 15 bulles de chat,
--      5 effets, 5 pets. NftCollectionsGrain.CountOwnedAsync ne compte que `furnitures` et
--      `nft_assets`, donc ces items-la ne seront JAMAIS possedes : les 106 collections qui en
--      contiennent ne pourront pas etre completees et leur boost ne tombera jamais. Les 137
--      autres fonctionnent entierement. C'est importe tel quel plutot que tronque : une
--      Rainbow Party a 1 item sur 8 n'est pas Rainbow Party.
--
--   2. item_type_id et product_type_id restent vides. C'est la regle de
--      CollectibleProductIdentity : le sprite id et la table sont derives de la definition de
--      meuble a l'envoi. Les ids d'Habbo ne sont pas les notres -- et pour les vetements, un
--      id de piece de figuredata n'est transposable d'aucune facon.
--
--   3. status = 1 (Visible) pour les 243. Habbo envoie 0, 1 ou 2 et les montre TOUTES ; sa
--      valeur correle avec la 2e date (status 2 <=> date de fin presente, 107 fois sur 110),
--      pas avec une visibilite. Nos trois valeurs sont les notres, documentees comme telles.
--
--   4. boost_score = le 3e entier du paquet. Il vaut total x nombre d'items pour les 243 sans
--      exception : c'est une formule, pas une donnee editoriale. Notre grain calcule ensuite
--      TotalScore = somme + boost, la ou Habbo envoie la somme seule -- un ecart d'affichage
--      assume, pas un bug d'import.
--
--   5. snapshot_at recoit une date de FERMETURE. La colonne est documentee comme << le moment
--      ou la possession a ete recensee >> ; les valeurs disent le contraire, et rien n'a ete
--      renomme. Sur les 110 collections datees elle tombe cinq a six semaines APRES released_at,
--      et vaut -1 sur les 133 perennes. La colonne est remplie telle quelle -- c'est la donnee
--      d'Habbo, pas une reinterpretation -- et le constat est verse dans la spec
--      collectibles.get_nft_collections.
--
--   6. Rarete normalisee en Capitale : Habbo envoie 'rare', 'uncommon' a cote de leurs equivalents
--      capitalises dans la meme liste. C'est notre donnee maintenant, pas un releve.
--
-- Idempotent : relancable sans doublon (collection_code unique, et (collection_id,
-- product_code) unique sur les items).

-- 1) Verification a blanc -- qu'y a-t-il deja ?
