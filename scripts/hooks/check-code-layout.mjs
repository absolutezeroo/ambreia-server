#!/usr/bin/env node
// The repository's layout rules, made executable (owner rules, 2026-10-08):
//
//   1. One top-level type per file. A type and its generic namesake (IRoomObject and
//      IRoomObject<…>) count as one; partial declarations of one type count as one.
//   2. A file's namespace is its folder: Vortex.Rooms/Grains/State/RoomLiveState.cs declares
//      `namespace Vortex.Rooms.Grains.State;`.
//
// Both were broken in about forty files before lot 3 of the clean-up put them right; nothing
// stopped them drifting back but memory.
//
//   node scripts/hooks/check-code-layout.mjs
//   node scripts/hooks/check-code-layout.mjs --update   # re-baseline the known exceptions
//
// Exit 2 = a new violation. Exit 0 = the layout holds.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const baselineFile =
  process.env.VORTEX_LAYOUT_BASELINE ??
  path.join(root, 'scripts', 'hooks', 'code-layout-baseline.json');
const update = process.argv.includes('--update');

const rel = (p) => path.relative(root, p).split(path.sep).join('/');

const files = [];
for (const project of fs.readdirSync(root)) {
  const dir = path.join(root, project);
  if (!project.startsWith('Vortex.') || !fs.statSync(dir).isDirectory()) continue;
  const walk = (d) => {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      // Migrations are generated by EF and keep its layout.
      if (['obj', 'bin', 'Migrations', 'TestResults'].includes(e.name)) continue;
      const p = path.join(d, e.name);
      if (e.isDirectory()) walk(p);
      else if (e.name.endsWith('.cs')) files.push(p);
    }
  };
  walk(dir);
}

// A top-level declaration starts at column 0 (file-scoped namespaces); a nested one is indented.
const typeDecl =
  /^(?:\[[^\]]*\]\s*)*(?:(?:public|internal|private|protected|file|static|sealed|abstract|readonly|partial|unsafe|ref|new)\s+)*(?:record\s+(?:class|struct)|class|record|interface|struct|enum|delegate\s+[\w<>?,\s\[\]]+?)\s+@?([A-Za-z_]\w*)/;

const violations = [];

for (const file of files) {
  const text = fs.readFileSync(file, 'utf8').replace(/^﻿/, '');
  const lines = text.split(/\r?\n/);
  const names = new Set();
  let inBlockComment = false;

  for (const line of lines) {
    if (inBlockComment) {
      if (line.includes('*/')) inBlockComment = false;
      continue;
    }
    if (/^\s*\/\*/.test(line) && !line.includes('*/')) {
      inBlockComment = true;
      continue;
    }
    const m = line.match(typeDecl);
    if (m) names.add(m[1]);
  }

  if (names.size > 1) {
    violations.push(`types  ${rel(file)}: ${[...names].join(', ')}`);
  }

  const ns = text.match(/^namespace\s+([\w.]+)\s*;/m)?.[1];
  if (ns) {
    const expected = path
      .relative(root, path.dirname(file))
      .split(path.sep)
      .join('.');
    if (ns !== expected) {
      violations.push(`folder ${rel(file)}: namespace ${ns}, folder ${expected}`);
    }
  }
}

if (update) {
  fs.writeFileSync(baselineFile, `${JSON.stringify(violations.sort(), null, 2)}\n`);
  console.log(`check-code-layout: baseline written (${violations.length} known exception(s)).`);
  process.exit(0);
}

const baseline = new Set(
  fs.existsSync(baselineFile) ? JSON.parse(fs.readFileSync(baselineFile, 'utf8')) : []
);
const fresh = violations.filter((v) => !baseline.has(v));

if (fresh.length > 0) {
  console.error('check-code-layout: the layout rules are broken.\n');
  for (const v of fresh) console.error(`  ${v}`);
  console.error(
    '\nOne top-level type per file, in the folder its namespace names. Split the file, or move it' +
      ' (git mv) and fix its namespace.'
  );
  process.exit(2);
}

console.log(
  `check-code-layout: OK (${files.length} files; ${baseline.size} known exception(s) baselined).`
);
