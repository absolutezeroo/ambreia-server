using System;
using System.Collections.Generic;
using System.Linq;
using System.Text.RegularExpressions;
using FluentAssertions;
using Vortex.Database.Seeds;
using Vortex.Progression.Achievements;
using Xunit;

namespace Vortex.Database.Tests.Achievements;

/// <summary>
/// What <c>achievement_catalogue.sql</c> has to hold for the achievement window to work.
/// </summary>
/// <remarks>
/// <para>
/// None of this is caught by anything else: the rows insert, the wire is well-formed, the badge is
/// granted, and the client draws a missing image under a raw localization key. That is how all 35
/// hand-seeded achievements shipped with five levels each — a figure taken from nothing — and how
/// six of them ended up with four levels the client cannot name.
/// </para>
/// <para>
/// The catalogue is generated by <c>tools/achievement_catalogue/build.py</c> from the client's
/// <c>external_flash_texts</c> and the Habbox wiki, neither of which is in this repository, so
/// what the generator guarantees is asserted here against its output.
/// </para>
/// </remarks>
public sealed class AchievementSeedLevelTests
{
    /// <summary>
    /// The categories the client has a <c>quests.&lt;category&gt;.name</c> key for. A value outside
    /// this list captions the tab with the raw key; <c>avatar</c> and <c>build</c>, seeded by the
    /// original migrations, are two that did.
    /// </summary>
    private static readonly string[] NameableCategories =
    [
        "explore",
        "identity",
        "social",
        "room_builder",
        "games",
        "pets",
        "music",
        "tools",
        "tutorial",
        "crackables",
        "crafting",
        "trading",
        "collectibles",
        "archive",
        "wired_games",
    ];

    /// <summary>
    /// Families whose only <c>badge_name_</c> key is level 1: the client has no level-less
    /// <c>%roman%</c> key for them, so a second level would render as the key itself.
    /// </summary>
    private static readonly string[] SingleLevelFamilies =
    [
        "Motto",
        "AvatarLooks",
        "Name",
        "AvatarTags",
        "EmailVerification",
        "HappyHour",
    ];

    private sealed record Level(string Family, string Category, int Number, int Requirement);

    private static readonly IReadOnlyList<Level> Catalogue = Parse();

    private static IReadOnlyList<Level> Parse() =>
        [
            .. Regex
                .Matches(
                    SeedScripts.Read("achievement_catalogue.sql"),
                    @"\('(?<family>[A-Za-z]+)', '(?<category>[a-z_]+)', (?<level>\d+), 'ACH_\k<family>\k<level>', (?<requirement>\d+),"
                )
                .Select(m => new Level(
                    m.Groups["family"].Value,
                    m.Groups["category"].Value,
                    int.Parse(m.Groups["level"].Value),
                    int.Parse(m.Groups["requirement"].Value)
                )),
        ];

    private static ILookup<string, Level> ByFamily => Catalogue.ToLookup(l => l.Family);

    [Fact]
    public void TheCatalogueParses()
    {
        // The badge code is matched against the family and level in the regex itself, so a row
        // whose code disagrees with its own columns does not parse and is missing from the count.
        Catalogue.Should().HaveCountGreaterThan(1000);
        ByFamily.Should().HaveCountGreaterThan(100);
    }

    [Fact]
    public void EveryFamilyStartsAtLevelOneAndHasNoGap()
    {
        foreach (IGrouping<string, Level> family in ByFamily)
        {
            family
                .Select(l => l.Number)
                .OrderBy(n => n)
                .Should()
                .Equal(
                    Enumerable.Range(1, family.Count()),
                    "'{0}' is walked level by level from 1",
                    family.Key
                );
        }
    }

    [Fact]
    public void EveryFamilyAsksForMoreAtEachLevel()
    {
        // ApplyProgress completes every level whose requirement the new total reaches, so two
        // levels sharing a requirement are cleared by one point of progress and the badge of the
        // first is granted and removed in the same breath.
        foreach (IGrouping<string, Level> family in ByFamily)
        {
            int[] requirements = [.. family.OrderBy(l => l.Number).Select(l => l.Requirement)];

            requirements
                .Zip(requirements.Skip(1))
                .Should()
                .OnlyContain(
                    pair => pair.First < pair.Second,
                    "'{0}' must ask for strictly more at each level",
                    family.Key
                );
        }
    }

    [Fact]
    public void EveryCategoryIsOneTheClientCanName() =>
        Catalogue.Select(l => l.Category).Distinct().Should().BeSubsetOf(NameableCategories);

    [Fact]
    public void TheFamiliesTheClientNamesOnlyAtLevelOneHaveOneLevel()
    {
        foreach (string family in SingleLevelFamilies)
        {
            ByFamily[family]
                .Should()
                .HaveCountLessThanOrEqualTo(1, "'{0}' has no badge_name key past level 1", family);
        }
    }

    [Fact]
    public void EveryNameTheConsumersCreditIsInTheCatalogue()
    {
        // The name is the only link between a trigger and a row: PlayerAchievementGrain resolves
        // it by name and logs a warning on a miss, so a mismatch is a bar that never moves and
        // nothing that fails. 'FriendCount' was seeded, 'FriendListSize' was credited, and
        // accepting a friend advanced nothing.
        string[] credited =
        [
            AchievementNames.Login,
            AchievementNames.RoomEntry,
            AchievementNames.Motto,
            AchievementNames.AvatarLooks,
            AchievementNames.FriendListSize,
            AchievementNames.RoomDecoFurniCount,
            AchievementNames.RespectGiven,
            AchievementNames.RespectEarned,
            AchievementNames.Name,
            AchievementNames.GiftGiver,
            AchievementNames.PetLevelUp,
            AchievementNames.PetLover,
        ];

        HashSet<string> seeded = [.. Catalogue.Select(l => l.Family)];

        credited.Should().OnlyContain(name => seeded.Contains(name));
    }
}
